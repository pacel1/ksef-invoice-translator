/**
 * Regenerates lib/landing/showcase-qr.ts — the static QR matrix shown on the
 * landing hero invoice (InvoiceShowcase). Run after changing the target URL:
 *
 *   node scripts/generate-showcase-qr.mjs
 *
 * The URL is uppercased on purpose: QR alphanumeric mode only covers uppercase
 * letters, and using it keeps the code at version 1 (21x21 modules), the
 * smallest grid there is. At the hero's 42px render size that is the
 * difference between a code phones scan and one they refuse. Scheme and host
 * are case-insensitive, so HTTPS://TLUMACZKSEF.PL resolves like the lowercase
 * form. Error correction stays at L for the same reason: an on-screen code
 * never gets damaged, so denser correction would only waste modules.
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import QRCode from "qrcode";

const QR_TEXT = "HTTPS://TLUMACZKSEF.PL";
const EC_LEVEL = "L";

const qr = QRCode.create(QR_TEXT, { errorCorrectionLevel: EC_LEVEL });
const size = qr.modules.size;

const rows = Array.from({ length: size }, (_, y) =>
  Array.from({ length: size }, (_, x) => (qr.modules.get(y, x) ? "1" : "0")).join("")
);

const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "lib",
  "landing",
  "showcase-qr.ts"
);

const file = `/**
 * AUTO-GENERATED by scripts/generate-showcase-qr.mjs — do not edit by hand.
 *
 * Static QR matrix for the landing hero invoice. Encodes ${QR_TEXT}
 * (uppercase keeps the code in alphanumeric mode -> version 1, 21x21 modules,
 * the smallest and therefore most scannable grid at the hero's 42px size).
 * Verified against the qrcode library in tests/lib/landing/showcase-qr.test.ts.
 */
import type { QRCodeErrorCorrectionLevel } from "qrcode";

export const SHOWCASE_QR_TEXT = ${JSON.stringify(QR_TEXT)};
export const SHOWCASE_QR_EC_LEVEL: QRCodeErrorCorrectionLevel = ${JSON.stringify(EC_LEVEL)};
export const SHOWCASE_QR_SIZE = ${size};

/** Row-major matrix; "1" is a dark module. */
export const SHOWCASE_QR_ROWS: readonly string[] = [
${rows.map((row) => `  ${JSON.stringify(row)}`).join(",\n")}
];
`;

await writeFile(outPath, file, "utf8");
process.stdout.write(`Wrote ${outPath} (${size}x${size}, EC ${EC_LEVEL})\n`);
